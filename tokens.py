#!/usr/bin/env python3
"""Design tokens for the whole rice: the one place radii, spacing, type, motion and glass levels live.

Python generators import TOKENS (Plasma Style, Klassy, ShapeCorners, Darkly, Konsole, boot), and
`tokens.py` writes them out as the QML singleton qml/Rice/Tokens.qml for the plasmoids.

    tokens.py            regenerate qml/Rice/Tokens.qml (rice.py does this on every run too)
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent

TOKENS = {
    # corner radii. md = bar islands = windows; lg = popups/dialogs; nested corners use outer - padding
    "radius": {"xs": 6, "sm": 10, "md": 14, "lg": 18, "xl": 24},
    "space": {"xxs": 2, "xs": 4, "sm": 8, "md": 12, "lg": 16, "xl": 24, "xxl": 32},
    "font": {"ui": "Inter", "display": "Inter Display", "mono": "JetBrainsMono Nerd Font",
             "icons": "Material Symbols Rounded"},
    # px sizes (QML font.pixelSize); the bars multiply by uiScale
    "size": {"caption": 10, "small": 11, "label": 12, "body": 13, "title": 15, "heading": 18,
             "display": 24, "hero": 32},
    # ms at normal speed; QML scales them by the system animation speed (kdeglobals AnimationDurationFactor)
    "dur": {"fast": 150, "base": 250, "slow": 400},
    # alpha levels over the palette's surfaces / accents
    "alpha": {"glass": 0.78, "card": 0.55, "hover": 0.08, "press": 0.14, "selected": 0.16,
              "outline": 0.10, "outlineStrong": 0.22, "wash": 0.12, "shadow": 0.45},
}

# colours used until a screen's palette has loaded (and for keys it lacks): dark Tokyo Night
FALLBACK = {
    "surface_lowest": "#16161e", "background": "#1a1b26", "surface": "#1a1b26", "surface_low": "#1f2030",
    "surface_container": "#24283b", "surface_high": "#292e42", "surface_highest": "#343a52",
    "outline_variant": "#3b4261", "outline": "#565f89", "muted": "#737aa2",
    "on_surface": "#c0caf5", "on_surface_variant": "#a9b1d6",
    "primary": "#7aa2f7", "primary_container": "#2c3e66", "on_primary": "#16161e", "on_primary_container": "#d6e2ff",
    "primary_dim": "#5d7ec4", "secondary": "#9aa5ce", "secondary_container": "#363d5a", "on_secondary": "#16161e",
    "tertiary": "#bb9af7", "tertiary_container": "#4a3a6b", "on_tertiary": "#16161e",
    "red": "#f7768e", "orange": "#ff9e64", "yellow": "#e0af68", "green": "#9ece6a", "teal": "#73daca",
    "cyan": "#7dcfff", "blue": "#7aa2f7", "magenta": "#bb9af7", "error": "#f7768e", "claude": "#d97757",
    "shadow": "#000000",
}


def qml():
    t = TOKENS
    def obj(d):
        return "({ " + ", ".join(f"{k}: {json.dumps(v)}" for k, v in d.items()) + " })"
    lines = [
        "pragma Singleton",
        "import QtQuick",
        "import org.kde.kirigami as Kirigami",
        "",
        "// GENERATED by ~/.config/plasma-rice/tokens.py: edit that file, not this one.",
        "// Design tokens shared by every rice widget (radii, spacing, type, motion, glass levels).",
        "QtObject {",
        f"    readonly property var radius: {obj(t['radius'])}",
        f"    readonly property var space: {obj(t['space'])}",
        f"    readonly property var font: {obj(t['font'])}",
        f"    readonly property var size: {obj(t['size'])}",
        f"    readonly property var alpha: {obj(t['alpha'])}",
        f"    readonly property var fallback: {obj(FALLBACK)}",
        "",
        "    // motion: the system animation speed (Kirigami's longDuration is 200 ms at normal speed,",
        "    // 0 when animations are off), so the widgets keep pace with KWin and stock Plasma",
        "    readonly property real speed: Kirigami.Units.longDuration / 200",
        "    function ms(d) { return Math.round(d * speed) }",
        *[f"    readonly property int {k}: ms({v})" for k, v in t["dur"].items()],
        "    readonly property int enter: Easing.OutCubic     // things arriving",
        "    readonly property int exit: Easing.InCubic       // things leaving",
        "    readonly property int move: Easing.InOutCubic    // things moving between states",
        "}",
    ]
    return "\n".join(lines) + "\n"


def write():
    out = HERE / "qml/Rice/Tokens.qml"
    out.parent.mkdir(parents=True, exist_ok=True)
    text = qml()
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
    return out


if __name__ == "__main__":
    print(write())
