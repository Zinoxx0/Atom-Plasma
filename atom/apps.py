DOLPHIN_TOOLBAR = """    <ToolBar noMerge="1" name="mainToolBar" ToolButtonStyle="icononly" >
        <text context="@title:menu">Main Toolbar</text>
        <Action name="go_back" />
        <Action name="go_forward" />
        <Action name="url_navigators" />
        <Action name="toggle_search" />
        <Action name="view_settings" />
        <Action name="hamburger_menu" />
    </ToolBar>"""


DOLPHIN_RC = ROOT / "atom/data/dolphinui.rc"            # Dolphin's dolphinui.rc with the rice toolbar
DOLPHIN_RC_FOR = ROOT / "atom/data/dolphinui.version"   # the Dolphin package it was taken from


def dolphin_version():
    return util.run("pacman", "-Q", "dolphin", quiet=True).stdout.split()[-1:] or [""]


def dolphin_refresh():
    """Take Dolphin's own dolphinui.rc again (after a Dolphin update) and put the rice toolbar in it:
    back/forward, the path, then search, view mode and the menu (split view stays on F3 and in the
    menu). The built-in file is a zstd-compressed Qt resource inside the binary; KXMLGUI ignores a
    local copy whose version is older than the app's, so a stale one does no harm, it just stops working."""
    blob, best = Path("/usr/bin/dolphin").read_bytes(), (-1, "")
    i = blob.find(b"\x28\xb5\x2f\xfd")
    while i >= 0:
        xml = util.run_bytes(["zstd", "-dcq"], blob[i:i + 400000]).decode(errors="replace")
        m = re.search(r'<gui name="dolphin" version="(\d+)"', xml)
        if m and 'ToolBar noMerge="1" name="mainToolBar" >' in xml and int(m.group(1)) > best[0]:
            best = (int(m.group(1)), xml)   # the desktop file (a phone layout with a bottom toolbar ships too)
        i = blob.find(b"\x28\xb5\x2f\xfd", i + 1)
    if best[0] < 0:
        sys.exit("dolphin-refresh: no dolphinui.rc found in /usr/bin/dolphin")
    ui = re.sub(r'    <ToolBar noMerge="1" name="mainToolBar" >.*?</ToolBar>', DOLPHIN_TOOLBAR, best[1], count=1, flags=re.S)
    util.write_if_changed(DOLPHIN_RC, ui)
    util.write_if_changed(DOLPHIN_RC_FOR, dolphin_version()[0] + "\n")
    print(f"dolphinui.rc version {best[0]}, from Dolphin {dolphin_version()[0]}")


def setup():
    if DOLPHIN_RC.exists():
        util.write_if_changed(HOME / ".local/share/kxmlgui5/dolphin/dolphinui.rc", DOLPHIN_RC.read_text())
        made_for = DOLPHIN_RC_FOR.read_text().strip() if DOLPHIN_RC_FOR.exists() else ""
        if made_for != dolphin_version()[0]:
            util.warn("Dolphin is %s, the rice toolbar was made for %s: run `apps.py dolphin-refresh`, then setup",
                      dolphin_version()[0], made_for or "an unknown version")
    kde.kde_set("dolphinrc", {
        "General": {"ShowStatusBar": "Small", "ShowZoomSlider": False,
                    "ShowSelectionToggle": False},
        "IconsMode": {"PreviewSize": 96, "IconSize": 64},
    })
    kde.kde_set("darklyrc", {"Style": {
        # the file view stays readable over a bright wallpaper; the sidebar shows more of the glass
        "DolphinViewOpacity": 72, "DolphinSidebarOpacity": 55,
        # the current tab gets a neutral lift, not a solid accent fill (accents are for state)
        "TabUseHighlightColor": False,
    }})


def apply(p):
    for fn in (vscode.apply_vscode, apply_btop, apply_mangohud, apply_zen, apply_fastfetch):
        try:
            fn(p)
        except Exception as e:  # one broken app must not stop the rest of the re-theme
            util.warn("apps: %s: %s", fn.__name__, e)


def palette_now():
    return json.loads((util.STATE / "palette.json").read_text())


def main(args):
    # setup, dolphin-refresh and konsole-chrome need no palette (konsole-chrome runs at login, maybe before there is one)
    if args == ["install-vscode"]:
        vscode.install_vscode(palette_now())
    elif args == ["setup"]:
        setup()
    elif args == ["dolphin-refresh"]:
        dolphin_refresh()
    elif args == ["konsole-chrome"]:
        terminals.konsole_chrome()
    elif not args:
        apply(palette_now())
    else:
        sys.exit(__doc__)
